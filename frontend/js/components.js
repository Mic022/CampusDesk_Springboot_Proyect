// Toast notification management system
const Toast = {
  container: null,

  init() {
    if (!this.container) {
      this.container = document.createElement('div');
      this.container.className = 'toast-container';
      document.body.appendChild(this.container);
    }
  },

  show(type, title, message, duration = 4000) {
    this.init();
    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    toast.innerHTML = `
      <div class="toast-content">
        <div class="toast-title">${title}</div>
        <div class="toast-message">${message}</div>
      </div>
      <button class="toast-close" aria-label="Close notification">&times;</button>
    `;

    toast.querySelector('.toast-close').addEventListener('click', () => {
      toast.remove();
    });

    this.container.appendChild(toast);

    if (duration > 0) {
      setTimeout(() => {
        toast.classList.add('toast-leaving');
        setTimeout(() => toast.remove(), 300);
      }, duration);
    }
  },

  success(title, message) { this.show('success', title, message); },
  error(title, message) { this.show('error', title, message); },
  warning(title, message) { this.show('warning', title, message); },
  info(title, message) { this.show('info', title, message); }
};

// Modal dialog system
const Modal = {
  currentOverlay: null,

  open({ title, content, confirmText = 'Confirm', cancelText = 'Cancel', onConfirm = null }) {
    this.close(); // Close any currently open modal

    const overlay = document.createElement('div');
    overlay.className = 'modal-overlay';
    overlay.innerHTML = `
      <div class="modal-box" role="dialog" aria-modal="true">
        <div class="modal-header">
          <div class="modal-title">${title}</div>
          <button class="modal-close-btn" aria-label="Close modal">&times;</button>
        </div>
        <div class="modal-body">${content}</div>
        <div class="modal-footer">
          <button class="btn btn-secondary modal-cancel-btn">${cancelText}</button>
          <button class="btn btn-primary modal-confirm-btn">${confirmText}</button>
        </div>
      </div>
    `;

    document.body.appendChild(overlay);
    this.currentOverlay = overlay;

    // Trigger active class for animation
    setTimeout(() => overlay.classList.add('active'), 10);

    const closeModal = () => this.close();
    overlay.querySelector('.modal-close-btn').addEventListener('click', closeModal);
    overlay.querySelector('.modal-cancel-btn').addEventListener('click', closeModal);
    overlay.addEventListener('click', (e) => {
      if (e.target === overlay) closeModal();
    });

    overlay.querySelector('.modal-confirm-btn').addEventListener('click', () => {
      if (onConfirm) onConfirm();
      closeModal();
    });

    document.addEventListener('keydown', function handleEsc(e) {
      if (e.key === 'Escape') {
        closeModal();
        document.removeEventListener('keydown', handleEsc);
      }
    });
  },

  close() {
    if (this.currentOverlay) {
      this.currentOverlay.classList.remove('active');
      setTimeout(() => {
        if (this.currentOverlay && this.currentOverlay.parentNode) {
          this.currentOverlay.parentNode.removeChild(this.currentOverlay);
        }
        this.currentOverlay = null;
      }, 250);
    }
  }
};

// Format ISO date strings into readable business date strings
function formatDate(dateStr) {
  if (!dateStr) return 'N/A';
  try {
    const d = new Date(dateStr);
    return d.toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit'
    });
  } catch (e) {
    return dateStr;
  }
}

// Generate HTML badge for ticket statuses
function getStatusBadge(status) {
  const norm = (status || 'OPEN').toUpperCase();
  const label = norm.replace('_', ' ');
  const cssClass = norm.toLowerCase().replace('_', '-');
  return `<span class="badge badge-status-${cssClass}" data-i18n="status_${norm.toLowerCase()}"><span class="badge-dot"></span>${label}</span>`;
}

// Generate HTML badge for ticket priorities
function getPriorityBadge(priority) {
  const norm = (priority || 'MEDIUM').toUpperCase();
  const cssClass = norm.toLowerCase();
  return `<span class="badge badge-priority-${cssClass}" data-i18n="priority_${norm.toLowerCase()}">${norm}</span>`;
}

// Smoothly dismiss initial splash loader screen
function dismissSplash() {
  const loader = document.getElementById('splash-loader');
  if (loader) {
    setTimeout(() => {
      loader.classList.add('hidden');
      setTimeout(() => loader.remove(), 400);
    }, 400);
  }
}
